// آدرس canonical همیشه بدون اسلش پایانی و بدون پسوند فایل ساخته می‌شود.
// صفحات پیش‌رندرشده به شکل dist/<route>/index.html نوشته می‌شوند، اما آپاچی
// (.htaccess) فرم دارای اسلش پایانی را با ۳۰۱ به فرم بدون اسلش هدایت می‌کند و
// همان مسیر بدون اسلش را داخلی از index.html سرو می‌کند. پس canonical باید به
// همین فرم بدون اسلش اشاره کند تا به آدرسی که خودش ریدایرکت می‌شود اشاره نکند.
export function pageUrl(path: string): string {
  // ریشه ('/') همان دامنه است؛ برای بقیه مسیرها اسلش پایانی حذف می‌شود.
  const clean = path === '/' ? '' : path.replace(/\/+$/, '');
  return `${siteConfig.domain}${clean}`;
}
